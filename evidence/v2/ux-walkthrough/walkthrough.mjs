// Portability adjustment for the public repository: use the installed package.
import { chromium } from 'playwright';
import fs from 'node:fs/promises';
const dir = new URL('./', import.meta.url);
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const log=[];
const shot=async name=>page.screenshot({path:new URL(name,dir).pathname.replace(/^\/(\w:)/,'$1'),fullPage:false});
await page.goto('http://127.0.0.1:4173/', {waitUntil:'networkidle'});
log.push({step:'Entry',visible:await page.locator('body').innerText(),url:page.url()});
await shot('01-entry-viewport.png');
await page.getByRole('link',{name:'留個位置給我'}).click();
await page.waitForTimeout(700);
await shot('02-register.png');
log.push({step:'Clicked reserve seat',url:page.url(),form:await page.locator('form').innerText()});
await page.getByLabel('怎麼稱呼你').fill('測試參與者');
await page.getByLabel('Email',{exact:true}).fill('participant@example.com');
await shot('03-filled.png');
await page.getByRole('button',{name:'我要參加'}).click();
await page.waitForTimeout(500);
await shot('04-submit.png');
log.push({step:'Submitted fictitious valid fields',visible:await page.locator('body').innerText()});
await fs.writeFile(new URL('walkthrough-log.json',dir),JSON.stringify(log,null,2));
console.log(JSON.stringify(log,null,2));
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
await shot('05-mobile-entry.png');
await page.getByRole('link',{name:'留個位置給我'}).click();
await page.waitForTimeout(700);
await shot('06-mobile-register.png');
await page.getByLabel('怎麼稱呼你').fill('測試參與者');
await page.getByLabel('Email',{exact:true}).fill('participant@example.com');
await page.getByRole('button',{name:'我要參加'}).click();
await page.waitForTimeout(500);
await shot('07-mobile-submit.png');
log.push({step:'Mobile submitted same fields',visible:await page.locator('body').innerText()});
await fs.writeFile(new URL('walkthrough-log.json',dir),JSON.stringify(log,null,2));
await browser.close();
